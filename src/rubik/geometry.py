"""リストの添字 (面, 縦, 横) と、3次元空間の位置との対応表。

3Dグラフィクスを描くときに使う。テストでも使う。

空間の向きは次のように取る。

    x が増える向き = R (右) の方向
    y が増える向き = U (上) の方向
    z が増える向き = F (手前) の方向

キューブは 3x3x3 個の小立方体でできていて、中心を原点に置くと、
それぞれの小立方体の位置は x, y, z がそれぞれ -1, 0, 1 のどれかで表せる。
"""

from .cube import UP, LEFT, FRONT, RIGHT, BACK, DOWN

# 面ごとの向きの情報。
#
#   normal  ... その面が外を向いている方向
#   row_dir ... 縦座標 row が 1 増えたときに進む方向
#   col_dir ... 横座標 col が 1 増えたときに進む方向
#
# たとえば F 面は手前 (+z) を向いていて、row が増えると下 (-y) へ、
# col が増えると右 (+x) へ進む。cube.py で決めた「外側から見て
# 左上が (0,0)」という約束をそのまま数字にしただけ。
FACE_BASIS = {
    UP:    ((0, 1, 0),  (0, 0, 1),  (1, 0, 0)),
    LEFT:  ((-1, 0, 0), (0, -1, 0), (0, 0, 1)),
    FRONT: ((0, 0, 1),  (0, -1, 0), (1, 0, 0)),
    RIGHT: ((1, 0, 0),  (0, -1, 0), (0, 0, -1)),
    BACK:  ((0, 0, -1), (0, -1, 0), (-1, 0, 0)),
    DOWN:  ((0, -1, 0), (0, 0, -1), (1, 0, 0)),
}


def cubie_position(face, row, col):
    """ステッカー (face, row, col) が貼られている小立方体の位置を返す。

    返り値は (x, y, z) で、それぞれ -1, 0, 1 のどれか。
    """
    normal, row_dir, col_dir = FACE_BASIS[face]
    return tuple(
        normal[i] + row_dir[i] * (row - 1) + col_dir[i] * (col - 1)
        for i in range(3)
    )


def sticker_corners(face, row, col, size=0.46):
    """ステッカーを四角形として描くための、4つの角の座標を返す。

    小立方体の1辺を 1 とすると、キューブの表面は中心から 1.5 のところにある。
    size はステッカーの半径ぶん。1辺の半分 (0.5) より少し小さくして、
    ステッカーどうしのすきま (黒い線) を作っている。
    """
    normal, row_dir, col_dir = FACE_BASIS[face]

    center = [
        normal[i] * 1.5 + row_dir[i] * (row - 1) + col_dir[i] * (col - 1)
        for i in range(3)
    ]

    corners = []
    for a, b in ((-1, -1), (-1, 1), (1, 1), (1, -1)):
        corners.append(tuple(
            center[i] + row_dir[i] * a * size + col_dir[i] * b * size
            for i in range(3)
        ))
    return corners


